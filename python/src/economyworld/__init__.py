"""EconomyWorld -- balances, bookings, inventories and trades, calculated, never stored.

Play money only: no real currency, no payout, no payment provider, no random
payouts. See the README for why each of those is deliberately absent.

    >>> from economyworld import EconomyEngine, create_currency, member_account, empty_account
    >>> engine = EconomyEngine(currencies=[create_currency("COIN")])
    >>> ana = empty_account(member_account("guild-1", "ana", "COIN"))
    >>> result = engine.credit(ana, 500, now=1_700_000_000_000, operation_id="op-1", reason="welcome gift")
    >>> result.balances["guild-1/ana/COIN"]
    500

The posting in ``result.posting`` must be written in a **single database
transaction**, every line of it. That is the one obligation this package cannot
take off your hands -- see :mod:`economyworld.ledger`.
"""

